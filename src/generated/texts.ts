// What generated output is made of (spec §15 Generated output per worktree;
// ADR 0002, ADR 0010): per served evolved skill, the byte-exact copy in the
// dotfolder and one stub per client pointing at it, each in a folder that
// ignores itself so nobody commits it on any branch.
//
// The stub bodies follow the P2 spike verdicts: Claude Code matched §15's
// body verbatim (spike C), so its stub keeps it; Codex's half couldn't be
// verified (spike F), so its stub takes the fallback and leads with a
// `skill_read` call, the copy becoming the second step.
import { serializeSkillText, STUB_PREFIX } from '../knowledge';

/** Every generated folder's own `.gitignore`: it ignores everything in the folder, itself included. */
export const GENERATED_GITIGNORE = '*\n';

/** Where the copies live: `.grimoire/skills/<name>/SKILL.md`. */
export const COPY_ROOT = '.grimoire/skills';

/** Which agent client a stub serves. */
export type StubClient = 'claude-code' | 'codex';

/** Where each client discovers skills: `<root>/grimoire-<name>/SKILL.md`. */
export const STUB_ROOTS: Readonly<Record<StubClient, string>> = { 'claude-code': '.claude/skills', codex: '.agents/skills' };

/**
 * The shipped chore carriers' folder name in both stub roots. They are
 * manifest entries `init` writes, never generated output: exempt from every
 * rule here (spec §15, `grimoire-*` folders).
 */
export const CHORE_CARRIER = `${STUB_PREFIX}chores`;

/** A skill's file in each generated folder. */
export const SKILL_FILE = 'SKILL.md';

/** What one served skill gives a stub. */
export interface StubSource {
  readonly name: string;
  readonly description: string;
}

/** POSIX path, relative to the worktree, of skill `name`'s copy folder. */
export function copyFolder(name: string): string {
  return `${COPY_ROOT}/${name}`;
}

/** POSIX path, relative to the worktree, of skill `name`'s stub folder for `client`. */
export function stubFolder(client: StubClient, name: string): string {
  return `${STUB_ROOTS[client]}/${STUB_PREFIX}${name}`;
}

const ABSENT_LINE =
  "If `.grimoire/config.yml` is absent in this checkout, grimoire isn't installed here: ignore this skill, and tell the user that `npx @goksening/grimoire leave` cleans these files up.";

/** The stub body each client gets for skill `name`. */
function stubBody(client: StubClient, name: string): string {
  const copy = `\`${copyFolder(name)}/${SKILL_FILE}\``;
  const lines =
    client === 'claude-code'
      ? [`Generated by grimoire. Read and follow ${copy}.`, `If that file is missing, call \`skill_read\` with \`${name}\`.`]
      : [`Generated by grimoire. Call \`skill_read\` with \`${name}\` and follow what it returns.`, `If \`skill_read\` is unavailable, read and follow ${copy}.`];
  return `\n${[...lines, ABSENT_LINE].join('\n\n')}\n`;
}

/** Skill `source`'s stub for `client`: the prefixed name, the copied description, and the body pointing at the copy. */
export function stubText(client: StubClient, source: StubSource): string {
  return serializeSkillText({ name: `${STUB_PREFIX}${source.name}`, description: source.description, body: stubBody(client, source.name) });
}
