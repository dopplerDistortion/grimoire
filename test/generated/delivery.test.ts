/** The Claude Code stub, in §15's words (spike C confirmed P2 for Claude Code verbatim). */
const CLAUDE_STUB = `---
name: grimoire-release-notes
description: ${NOTES_DESCRIPTION}
---

Generated by grimoire. Read and follow \`.grimoire/skills/release-notes/SKILL.md\`.

If that file is missing, call \`skill_read\` with \`release-notes\`.

If \`.grimoire/config.yml\` is absent in this checkout, grimoire isn't installed here: ignore this skill, and tell the user that \`npx @goksening/grimoire leave\` cleans these files up.
`;

/** The Codex stub: spike F took P2's fallback, so it leads with a `skill_read` call. */
const CODEX_STUB = `---
name: grimoire-release-notes
description: ${NOTES_DESCRIPTION}
---

Generated by grimoire. Call \`skill_read\` with \`release-notes\` and follow what it returns.

If \`skill_read\` is unavailable, read and follow \`.grimoire/skills/release-notes/SKILL.md\`.

If \`.grimoire/config.yml\` is absent in this checkout, grimoire isn't installed here: ignore this skill, and tell the user that \`npx @goksening/grimoire leave\` cleans these files up.
`;

describe('copies and stubs in every worktree on this pin', () => {
  test('a skill edit makes the copy and both stubs appear in A and B (this pin), not in C (another pin), and git status stays clean everywhere', async ({
    world,
    grimoire,
  }) => {
    await pinAndCommit(world.a);
    const b = await world.a.addWorktree('b');
    const c = await world.a.addWorktree('c');
    await pinAndCommit(c, '9.9.9');
    const core = grimoire.makeCore();

    await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });
    // The deciding process refreshes its same-pin worktrees after the call answers.
    await core.close();

    for (const wt of [world.a, b]) {
      expect(await fileIn(wt, '.grimoire/skills/release-notes/SKILL.md'), wt.dir).toBe(NOTES);
      expect(await fileIn(wt, '.claude/skills/grimoire-release-notes/SKILL.md'), wt.dir).toBe(CLAUDE_STUB);
      expect(await fileIn(wt, '.agents/skills/grimoire-release-notes/SKILL.md'), wt.dir).toBe(CODEX_STUB);
      for (const folder of ['.grimoire/skills/release-notes', '.claude/skills/grimoire-release-notes', '.agents/skills/grimoire-release-notes']) {
        expect(await fileIn(wt, `${folder}/.gitignore`), folder).toBe('*\n');
      }
    }
    await expectNoOutput(c, 'release-notes');
    for (const wt of [world.a, b, c]) expect(await gitStatus(wt), wt.dir).toBe('');
  });
});

/** A chore carrier as `init` writes it: a manifest entry, never generated output. */
const CARRIER = '---\nname: grimoire-chores\ndescription: Run grimoire’s due knowledge chores.\n---\n\nRun them.\n';

describe('tracked paths, chore carriers and folders grimoire didn’t make', () => {
  test('a force-added copy is a tracked-path collision: reported and never touched, and its skill gets no stubs there; the chore carriers are never moved or flagged', async ({
    world,
    grimoire,
  }) => {
    await pinAndCommit(world.a);
    await world.a.commitFile('.claude/skills/grimoire-chores/SKILL.md', CARRIER);
    await writeInto(world.a.dir, '.agents/skills/grimoire-chores/SKILL.md', CARRIER);
    await writeInto(world.a.dir, '.grimoire/skills/release-notes/SKILL.md', 'my own notes skill\n');
    await world.a.git(['add', '--force', '.grimoire/skills/release-notes/SKILL.md']);
    await world.a.git(['commit', '--quiet', '-m', 'force-add a copy']);
    await editSkill(grimoire.makeCore({ refreshSkills: 'off' }), grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });

    const report = await runUpkeep({ root: world.a.dir });

    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe('my own notes skill\n');
    expect(await existsIn(world.a, '.grimoire/skills/release-notes/.gitignore')).toBe(false);
    expect(await existsIn(world.a, '.claude/skills/grimoire-release-notes')).toBe(false);
    expect(await existsIn(world.a, '.agents/skills/grimoire-release-notes')).toBe(false);
    const run = report.runs.find((entry) => entry.part === 'skill-reconcile');
    expect(run).toMatchObject({ status: 'ran', result: { collisions: ['.grimoire/skills/release-notes/SKILL.md'], moved_aside: [] } });
    expect(report.notices).toContainEqual(expect.stringContaining('tracked-path collision'));
    expect(report.notices).toContainEqual(expect.stringMatching(/release-notes reaches agents only through skill_list and skill_read/));
    // The carriers: where they were, as they were, and in no report.
    expect(await fileIn(world.a, '.claude/skills/grimoire-chores/SKILL.md')).toBe(CARRIER);
    expect(await fileIn(world.a, '.agents/skills/grimoire-chores/SKILL.md')).toBe(CARRIER);
    expect(JSON.stringify(report)).not.toContain('grimoire-chores');
  });

  test('an untracked grimoire-* folder that isn’t on the list and lacks grimoire’s .gitignore is moved into the machine-local store and reported; one with it is grimoire’s', async ({
    world,
    grimoire,
  }) => {
    await pinAndCommit(world.a);
    await writeInto(world.a.dir, '.claude/skills/grimoire-mine/SKILL.md', 'hand-made\n');
    await writeInto(world.a.dir, '.agents/skills/grimoire-release-notes/SKILL.md', 'also hand-made\n');
    await writeInto(world.a.dir, '.agents/skills/grimoire-retired/SKILL.md', 'an old stub\n');
    await writeInto(world.a.dir, '.agents/skills/grimoire-retired/.gitignore', '*\n');
    await editSkill(grimoire.makeCore({ refreshSkills: 'off' }), grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });

    const report = await runUpkeep({ root: world.a.dir });

    const moved = report.runs.find((entry) => entry.part === 'skill-reconcile')?.result as { moved_aside: { path: string; to: string }[] };
    expect(moved.moved_aside.map((entry) => entry.path).sort()).toEqual(['.agents/skills/grimoire-release-notes', '.claude/skills/grimoire-mine']);
    const store = path.join(world.a.dir, '.git', 'grimoire');
    for (const entry of moved.moved_aside) expect(path.relative(store, entry.to).startsWith('..'), entry.to).toBe(false);
    const mine = moved.moved_aside.find((entry) => entry.path === '.claude/skills/grimoire-mine')!;
    expect(await fileIn(mine.to, 'SKILL.md')).toBe('hand-made\n');
    expect(report.notices).toContainEqual(expect.stringContaining('grimoire moved .claude/skills/grimoire-mine to'));
    // The stub took the place of the folder moved aside; grimoire's own retired stub is gone.
    expect(await fileIn(world.a, '.agents/skills/grimoire-release-notes/SKILL.md')).toContain('name: grimoire-release-notes');
    expect(await existsIn(world.a, '.claude/skills/grimoire-mine')).toBe(false);
    expect(await existsIn(world.a, '.agents/skills/grimoire-retired')).toBe(false);
    expect(await gitStatus(world.a)).toBe('');
  });
});

/** Records one skill change as a decision op will (the dashboard's accept, record, …), in `checkout`'s tracker. */
async function decide(checkout: Checkout, identity: { name: string; email: string }, change: SkillChange): Promise<void> {
  const store = await openTracker(checkout.dir);
  try {
    const actor = { kind: 'human', client: 'dashboard', nonce: 'n' };
    await store.transact({ op: change.kind, author: identity, actor }, async (draft) => {
      await writeSkillChange(draft, scanner, change, { actor, by: identity.email, surface: 'dashboard', clone: 'c10e00000000000a' });
      return { result: null };
    });
  } finally {
    await store.close();
  }
}

describe('what is served', () => {
  test('a version failing the content checks is served nowhere, and the previous version keeps serving', async ({ world, grimoire }) => {
    await pinAndCommit(world.a);
    const core = grimoire.makeCore();
    await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });
    await core.close();
    const marked = skillText('release-notes', NOTES_DESCRIPTION, '# Release notes\n\n<<<<<<< ours\nOne.\n=======\nTwo.\n>>>>>>> theirs\n');
    const leaky = skillText('leaky', 'Use when deploying.', `export GITHUB_TOKEN=ghp_${'Z9y8X7w6V5u4'.repeat(3)}\n`);

    await decide(world.a, world.a.identity, { kind: 'record', skill: 'release-notes', text: marked });
    await decide(world.a, world.a.identity, { kind: 'accept', skill: 'leaky', text: leaky, proposal: 'p1' });
    await runUpkeep({ root: world.a.dir, force: true });

    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES);
    expect(await fileIn(world.a, '.claude/skills/grimoire-release-notes/SKILL.md')).toBe(CLAUDE_STUB);
    expect(await fileIn(world.a, '.agents/skills/grimoire-release-notes/SKILL.md')).toBe(CODEX_STUB);
    await expectNoOutput(world.a, 'leaky');
    expect(await core.call('skill_list', {}, grimoire.ctx)).toEqual({ ok: true, result: { skills: [{ name: 'release-notes', description: NOTES_DESCRIPTION }] } });
    expect(await core.call('skill_read', { name: 'leaky' }, grimoire.ctx)).toMatchObject({ ok: false, error: { code: 'NOT_FOUND' } });
  });

  test('with delivery off every copy and stub is removed and skill_list is empty; on again, they come back', async ({ world, grimoire }) => {
    await pinAndCommit(world.a);
    const b = await world.a.addWorktree('b');
    const core = grimoire.makeCore();
    await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });
    await editSkill(core, grimoire.ctx, { name: 'tidy-imports', text: skillText('tidy-imports', 'Use when imports need sorting.', '# Tidy\n\nSort them.\n'), base: null });
    await core.close();

    const off = await core.call('settings_set', { key: 'skills.delivery', value: false }, terminal(grimoire.ctx));
    await core.close();

    expect(off).toMatchObject({ ok: true, result: { changed: true } });
    for (const wt of [world.a, b]) {
      await expectNoOutput(wt, 'release-notes');
      await expectNoOutput(wt, 'tidy-imports');
      // Codex watches only skill roots that existed when a session started (spike F, B2): the root stays.
      expect(await existsIn(wt, '.agents/skills')).toBe(true);
      expect(await gitStatus(wt)).toBe('');
    }
    expect(await core.call('skill_list', {}, grimoire.ctx)).toEqual({ ok: true, result: { skills: [] } });

    await core.call('settings_set', { key: 'skills.delivery', value: true }, terminal(grimoire.ctx));
    await core.close();

    for (const wt of [world.a, b]) {
      expect(await fileIn(wt, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES);
      expect(await fileIn(wt, '.agents/skills/grimoire-tidy-imports/SKILL.md')).toContain('name: grimoire-tidy-imports');
    }
  });

  test('a 55-character skill name gives stubs named grimoire-<name>, 64 characters, matching their folders', async ({ world, grimoire }) => {
    await pinAndCommit(world.a);
    const name = `a${'-b'.repeat(27)}`;
    const core = grimoire.makeCore();
    await editSkill(core, grimoire.ctx, { name, text: skillText(name, 'Use when doing the thing.', '# Steps\n\nDo it.\n'), base: null });
    await core.close();

    for (const root of ['.claude/skills', '.agents/skills']) {
      const stub = await fileIn(world.a, `${root}/grimoire-${name}/SKILL.md`);
      const stubName = /^name: (.*)$/m.exec(stub ?? '')?.[1];
      expect(stubName, root).toBe(`grimoire-${name}`);
      expect(stubName!.length, root).toBe(64);
    }
  });

  test('a new version rewrites the copy byte for byte; a hand edit to the copy is saved as a stray edit, naming the version it was made on, before the served text goes back', async ({
    world,
    grimoire,
  }) => {
    await pinAndCommit(world.a);
    const core = grimoire.makeCore();
    const v1 = await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });
    await core.close();
    const edited = `${NOTES}\nAlso bump the version.\n`;
    await writeInto(world.a.dir, '.grimoire/skills/release-notes/SKILL.md', edited);

    const v2 = await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES_V2, base: v1.version });
    await core.close();

    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES_V2);
    const strays = await new MachineLocalStore(path.join(world.a.dir, '.git')).records.list<StrayEdit>(STRAY_EDITS);
    expect(strays.map((entry) => entry.value)).toEqual([
      expect.objectContaining({ skill: 'release-notes', text: edited, base: v1.version, served: v2.version, path: '.grimoire/skills/release-notes/SKILL.md' }),
    ]);

    // The old version's text in a copy is grimoire's own, never a stray edit.
    await writeInto(world.a.dir, '.grimoire/skills/release-notes/SKILL.md', NOTES);
    await runUpkeep({ root: world.a.dir, force: true });
    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES_V2);
    expect(await new MachineLocalStore(path.join(world.a.dir, '.git')).records.list(STRAY_EDITS)).toHaveLength(1);
  });
});

describe('who asks for a refresh', () => {
  test('a long-lived process’s refresh (its upkeep loop) is asked for by every write that changes the served set, and by no other', async ({ grimoire }) => {
    const asked: string[] = [];
    const core = grimoire.makeCore({ refreshSkills: ({ root }) => void asked.push(root) });
    const human = terminal(grimoire.ctx);

    const created = await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: null });
    await core.close();
    const steps = [asked.length];
    await editSkill(core, grimoire.ctx, { name: 'release-notes', text: NOTES, base: created.version });
    await core.call('settings_set', { key: 'skills.max_active', value: 5 }, human);
    await core.close();
    steps.push(asked.length);
    await core.call('settings_set', { key: 'skills.delivery', value: false }, human);
    await core.close();
    steps.push(asked.length);

    // The edit, then nothing for an unchanged edit or another setting, then the delivery switch.
    expect(steps).toEqual([1, 1, 2]);
    expect(asked).toEqual([grimoire.ctx.repo.root, grimoire.ctx.repo.root]);
  });
});

describe('reaching other clones', () => {
  test('a sync that brings another clone’s skill change refreshes this clone’s worktrees at once', async ({ world, grimoire }) => {
    await pinAndCommit(world.a);
    await pushTracker(world.a);
    await fetchTracker(world.b);
    await world.b.git(['update-ref', TRACKER_REF, 'refs/remotes/origin/grimoire/tracker']);
    const core = grimoire.makeCore();
    await editSkill(core, agentContext(world.b), { name: 'release-notes', text: NOTES, base: null });
    await pushTracker(world.b);
    await core.close();
    await expectNoOutput(world.a, 'release-notes');

    const synced = await core.call('sync', {}, terminal(grimoire.ctx));
    await core.close();

    expect(synced).toMatchObject({ ok: true });
    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES);
    expect(await fileIn(world.a, '.claude/skills/grimoire-release-notes/SKILL.md')).toBe(CLAUDE_STUB);
  });

  test('what is served comes from the merged view: a skill only the fetched remote-tracking tracker holds reaches this clone’s worktrees at the next upkeep', async ({
    world,
    grimoire,
  }) => {
    await pinAndCommit(world.a);
    await pushTracker(world.a);
    await fetchTracker(world.b);
    await world.b.git(['update-ref', TRACKER_REF, 'refs/remotes/origin/grimoire/tracker']);
    const core = grimoire.makeCore();
    await editSkill(core, agentContext(world.b), { name: 'release-notes', text: NOTES, base: null });
    await pushTracker(world.b);
    await core.close();
    // A plain `git fetch` brings it; nothing folds it into a's own tracker.
    await fetchTracker(world.a);

    await runUpkeep({ root: world.a.dir });

    expect(await fileIn(world.a, '.grimoire/skills/release-notes/SKILL.md')).toBe(NOTES);
    expect(await fileIn(world.a, '.agents/skills/grimoire-release-notes/SKILL.md')).toBe(CODEX_STUB);
  });
});
